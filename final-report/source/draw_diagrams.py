BLUE=('#eff6ff','#3b82f6'); PURPLE=('#f5f3ff','#8b5cf6'); GREEN=('#ecfdf5','#10b981'); RED=('#fff1f2','#f43f5e'); GRAY=('#f8fafc','#94a3b8')
class Diagram:
 def __init__(self,h,title,subtitle):
  self.p=[f'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="{h}" viewBox="0 0 1000 {h}" role="img"><title>{escape(title)}</title><defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0L10 5L0 10Z" fill="#64748b"/></marker></defs><rect width="1000" height="{h}" fill="white"/>']
  self.text(28,42,title,27,'#1e3a5f',True)
  self.text(28,73,subtitle,16,'#64748b')
 def text(self,x,y,s,size=18,color='#334155',bold=False,anchor='start'):
  self.p.append(f'<text x="{x}" y="{y}" font-family="Apple SD Gothic Neo, Arial, sans-serif" font-size="{size}" font-weight="{700 if bold else 400}" fill="{color}" text-anchor="{anchor}">{escape(s)}</text>')
 def box(self,x,y,w,h,title,lines=(),palette=BLUE):
  self.p.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" fill="{palette[0]}" stroke="{palette[1]}" stroke-width="2"/>')
  self.text(x+w/2,y+31,title,20,'#1e3a5f',True,'middle')
  for i,line in enumerate(lines): self.text(x+w/2,y+59+i*24,line,16,anchor='middle')
 def arrow(self,points,label='',lx=None,ly=None,dashed=False):
  path='M'+' L'.join(f'{x},{y}' for x,y in points)
  self.p.append(f'<path d="{path}" fill="none" stroke="#64748b" stroke-width="2" marker-end="url(#arrow)"'+(' stroke-dasharray="6 5"' if dashed else '')+'/>')
  if label:self.text(lx,ly,label,15,'#475569')
 def save(self,name): (OUT/name).write_text('\n'.join(self.p+['</svg>']))

